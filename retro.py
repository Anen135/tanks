class PixelFont:
    """Растеризует символы 5x7 в поверхности заданного цвета и масштаба."""

    def __init__(self):
        self.glyphs = {ch: rows.split("/") for ch, rows in FONT_SRC.items()}
        self.cache = {}
        self.advance = 6

    def glyph(self, ch, color, scale):
        key = (ch, color, scale)
        surf = self.cache.get(key)
        if surf is not None:
            return surf
        rows = self.glyphs.get(ch)
        if rows is None:
            rows = self.glyphs.get("?")
        surf = pygame.Surface((5 * scale, 7 * scale), pygame.SRCALPHA)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c != ".":
                    surf.fill(color, (x * scale, y * scale, scale, scale))
        self.cache[key] = surf
        return surf

    def width(self, text, scale=1):
        return max(0, len(text) * self.advance * scale - scale)

    def draw(self, dest, text, x, y, color=TEXT, scale=1, center=False, shadow=None):
        text = str(text).upper()
        w = self.width(text, scale)
        if center:
            x -= w // 2
        x, y = int(x), int(y)
        if shadow is not None:
            self.draw(dest, text, x + scale, y + scale, shadow, scale, False)
        for i, ch in enumerate(text):
            g = self.glyph(ch, color, scale)
            dest.blit(g, (x + i * self.advance * scale, y))
        return w

    def draw_shadowed(self, dest, text, x, y, color=TEXT, scale=1, center=False,
                      shadow=(0, 0, 0)):
        return self.draw(dest, text, x, y, color, scale, center, shadow)
